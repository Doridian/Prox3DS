#!/usr/bin/env python3
"""Writes nfcprobe/source/iclasskeys.c from pm3's client/dictionaries/iclass_default_keys.dic and
iclass_elite_keys.dic (iClass master keys; the app tries the defaults standard and elite, the elite
list elite).

usage: gen_iclasskeys.py [PATH/dictionaries]  (default: ~/Programming/RE/proxmark3/client/dictionaries)
The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.
"""
import os, re, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Programming/RE/proxmark3/client/dictionaries")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../nfcprobe/source/iclasskeys.c")


def keys(name):
    seen, res = set(), []
    for line in open(os.path.join(src, name), encoding="utf-8", errors="replace"):
        m = re.match(r"\s*([0-9A-Fa-f]{16})\s*(?:#\s*(.*))?$", line)
        if m and m.group(1).upper() not in seen:
            seen.add(m.group(1).upper())
            res.append((m.group(1).upper(), (m.group(2) or "").strip()))
    return res


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"')[:39] + '"'


def arr(k):
    return "{ " + ", ".join(f"0x{k[i:i + 2]}" for i in range(0, 16, 2)) + " }"


dflt, elite = keys("iclass_default_keys.dic"), keys("iclass_elite_keys.dic")
with open(out, "w", encoding="utf-8") as f:
    f.write("// iClass master keys: generated by tools/gen_iclasskeys.py from pm3's iclass_default_keys.dic and\n"
            "// iclass_elite_keys.dic. Don't edit.\n// The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.\n\n#include \"iclass.h\"\n\n")
    f.write("const IcDictKey icDefaultKeys[] = {\n")
    for k, label in dflt:
        f.write(f"\t{{ {arr(k)}, {c(label)} }},\n")
    f.write("};\nconst int icNumDefaultKeys = sizeof(icDefaultKeys) / sizeof(icDefaultKeys[0]);\n\n")
    f.write("const u8 icEliteKeys[][8] = {\n")
    for k, _ in elite:
        f.write(f"\t{arr(k)},\n")
    f.write("};\nconst int icNumEliteKeys = sizeof(icEliteKeys) / sizeof(icEliteKeys[0]);\n")
print(f"{len(dflt)} default + {len(elite)} elite keys -> {os.path.normpath(out)}")
