#!/usr/bin/env python3
"""Writes prox3ds/source/aidnames.c from pm3's client/resources/aid_desfire.json (DESFire AID names).

usage: gen_aidnames.py [PATH/aid_desfire.json]  (default: ~/Programming/RE/proxmark3/client/resources)
The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.
"""
import json, os, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Programming/RE/proxmark3/client/resources/aid_desfire.json")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../prox3ds/source/aidnames.c")


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


entries = sorted({int(e["AID"], 16): e for e in json.load(open(src, encoding="utf-8"))}.items())
with open(out, "w", encoding="utf-8") as f:
    f.write("// DESFire AID names: generated by tools/gen_aidnames.py from pm3's aid_desfire.json. Don't edit.\n// The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.\n\n")
    f.write('#include "desfire.h"\n\n')
    f.write("static const struct {\n\tu32 aid;\n\tconst char *vendor, *name;\n} names[] = {\n")
    for aid, e in entries:
        f.write(f"\t{{ 0x{aid:06X}, {c(e['Vendor'].strip())}, {c(e['Name'].strip())} }},\n")
    f.write("};\n\n")
    f.write("const char *dfAidName(u32 aid, const char **vendor)\n{\n")
    f.write("\tint lo = 0, hi = sizeof(names) / sizeof(names[0]) - 1;\n")
    f.write("\twhile (lo <= hi) {\n\t\tint m = (lo + hi) / 2;\n")
    f.write("\t\tif (names[m].aid == aid) {\n\t\t\tif (vendor) *vendor = names[m].vendor;\n\t\t\treturn names[m].name;\n\t\t}\n")
    f.write("\t\tif (names[m].aid < aid) lo = m + 1;\n\t\telse hi = m - 1;\n\t}\n\treturn NULL;\n}\n")
print(f"{len(entries)} AIDs -> {os.path.normpath(out)}")
