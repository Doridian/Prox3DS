#!/usr/bin/env python3
"""Writes prox3ds/source/madnames.c from pm3's client/resources/mad.json (MIFARE Application Directory
AIDs, NXP AN10787).

usage: gen_madnames.py [PATH/mad.json]  (default: ~/Programming/RE/proxmark3/client/resources)
The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.
"""
import json, os, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Programming/RE/proxmark3/client/resources/mad.json")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../prox3ds/source/madnames.c")


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


entries = {}
for e in json.load(open(src, encoding="utf-8")):
    entries.setdefault(int(e["mad"], 16), e)  # first one wins, as pm3's lookup
with open(out, "w", encoding="utf-8") as f:
    f.write("// MAD AID names: generated by tools/gen_madnames.py from pm3's mad.json. Don't edit.\n// The data is Proxmark3 (C) Proxmark3 contributors, GPL-3.0-or-later; see CREDITS.md.\n\n")
    f.write('#include "mfcinfo.h"\n\n')
    f.write("static const struct {\n\tu16 aid;\n\tconst char *company, *name;\n} names[] = {\n")
    for aid, e in sorted(entries.items()):
        f.write(f"\t{{ 0x{aid:04X}, {c(e['company'].strip())}, {c(e['application'].strip())} }},\n")
    f.write("};\n\n")
    f.write("const char *madAidName(u16 aid, const char **company)\n{\n")
    f.write("\tint lo = 0, hi = sizeof(names) / sizeof(names[0]) - 1;\n")
    f.write("\twhile (lo <= hi) {\n\t\tint m = (lo + hi) / 2;\n")
    f.write("\t\tif (names[m].aid == aid) {\n\t\t\tif (company) *company = names[m].company;\n\t\t\treturn names[m].name;\n\t\t}\n")
    f.write("\t\tif (names[m].aid < aid) lo = m + 1;\n\t\telse hi = m - 1;\n\t}\n\treturn NULL;\n}\n")
print(f"{len(entries)} AIDs -> {os.path.normpath(out)}")
