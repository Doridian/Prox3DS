#!/usr/bin/env python3
"""Writes nfcprobe/source/jcapitab.c / .h from the Java Card SDK's export files: every API package, its
classes by token (super, interfaces) and their methods by token, for the Java Card VM (jcvm.c) to link
CAP files against. Each method points at a weak native jn_<package>_<Class>_<method>[_<params>]: the
ones jcapi.c defines are linked, the rest stay NULL (calling one throws).

usage: gen_jcapi.py [EXPORT_DIR]  (default: ~/Applications/javacard/sdks/jc304_kit/api_export_files)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "jcvm"))
import exp  # noqa: E402

root = sys.argv[1] if len(sys.argv) > 1 else exp.EXP_DIR
src = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../nfcprobe/source")


def mangle(desc):
    """'([BSLjavacard/framework/AID;)V' -> 'aBSAID'"""
    out, i = "", 1
    while desc[i] != ")":
        if desc[i] == "[":
            out += "a"
            i += 1
        elif desc[i] == "L":
            j = desc.index(";", i)
            out += desc[i + 1:j].rsplit("/", 1)[-1]
            i = j + 1
        else:
            out += desc[i]
            i += 1
    return out


def cells(desc):
    n, i = 0, 1
    while desc[i] != ")":
        while desc[i] == "[":
            i += 1
        if desc[i] == "L":
            i = desc.index(";", i)
        n += 2 if desc[i] == "I" and desc[i - 1] != "[" else 1
        i += 1
    return n


pkgs = sorted(exp.load_all(root).values(), key=lambda p: p.name)
classes = []  # (pkg, ExpClass) in table order
for p in pkgs:
    for c in sorted(p.classes.values(), key=lambda c: c.token):
        classes.append((p, c))
index = {c.name: i for i, (p, c) in enumerate(classes)}


def ident(s):
    return s.replace("/", "_").replace("$", "_")


natives = []  # every jn_ name
out_c = ["// Java Card API link table: generated by tools/gen_jcapi.py from the SDK's export files. Don't edit.\n",
         '#include "jcvm.h"\n']
decls, tables = [], []
for i, (p, c) in enumerate(classes):
    short = p.name.rsplit("/", 1)[-1]
    simple = c.name.rsplit("/", 1)[-1]
    names = {}  # by C name: <init> and init(...) (KeyAgreement) count as overloads
    for (n, d) in c.methods:
        names.setdefault("init" if n == "<init>" else n, []).append(d)
    for kind in ("v", "s"):
        rows = []
        for (n, d), (tok, flags) in sorted(c.methods.items(), key=lambda kv: kv[1][0]):
            static = bool(flags & exp.ACC_STATIC)
            if (kind == "s") != (static or n == "<init>"):
                continue
            mname = "init" if n == "<init>" else n
            fn = "jn_%s_%s_%s" % (short, simple, mname)
            if len(names[mname]) > 1:
                fn += "_" + (mangle(d) or "V")
            natives.append(fn)
            decls.append("int %s(JcVm *vm, u16 *a) __attribute__((weak));" % fn)
            nargs = cells(d) + (0 if static else 1)
            rows.append('\t{ %d, %d, %s, "%s.%s%s" },' % (tok, nargs, fn, simple, n, d))
        if rows:
            tables.append("static const JcNativeMethod %s_%s[] = {\n%s\n};" % (kind, ident(c.name), "\n".join(rows)))
out_c.append("\n".join(decls) + "\n")
out_c.append("\n\n".join(tables) + "\n")

iface_rows = []
for i, (p, c) in enumerate(classes):
    if c.interfaces:
        iface_rows.append("static const s16 if_%s[] = { %s, -1 };" % (ident(c.name), ", ".join(str(index[n]) for n in c.interfaces)))
out_c.append("\n".join(iface_rows) + "\n")

rows = []
for i, (p, c) in enumerate(classes):
    nv = sum(1 for (n, d), (t, f) in c.methods.items() if not (f & exp.ACC_STATIC or n == "<init>"))
    ns = len(c.methods) - nv
    sup = index[c.supers[-1]] if c.supers else -1
    rows.append('\t{ "%s", %d, %d, %d, %s, %s, %d, %s, %d },' % (
        c.name, c.token, sup, int(c.interface), "if_" + ident(c.name) if c.interfaces else "NULL",
        "v_" + ident(c.name) if nv else "NULL", nv, "s_" + ident(c.name) if ns else "NULL", ns))
out_c.append("const JcApiClass jcApiClasses[JC_API_CLASSES] = {\n%s\n};\n" % "\n".join(rows))

rows, first = [], 0
for p in pkgs:
    n = len(p.classes)
    rows.append('\t{ (const u8 *)"%s", %d, %d, %d, %d, %d },' % (
        "".join("\\x%02X" % b for b in p.aid), len(p.aid), p.version[0], p.version[1], first, n))
    first += n
out_c.append("const JcApiPkg jcApiPkgs[JC_API_PKGS] = {\n%s\n};\n" % "\n".join(rows))

with open(os.path.join(src, "jcapitab.c"), "w") as f:
    f.write("\n".join(out_c))

h = ["// Java Card API classes and packages: generated by tools/gen_jcapi.py from the SDK's export files. Don't edit.",
     "#pragma once\n",
     "#define JC_API_CLASSES %d" % len(classes),
     "#define JC_API_PKGS    %d\n" % len(pkgs),
     "// jcApiClasses[] indices"]
for i, (p, c) in enumerate(classes):
    h.append("#define JCC_%s %d" % (ident(c.name).replace("javacardx_", "x_").replace("javacard_", "")
                                    .replace("java_lang_", "lang_"), i))
with open(os.path.join(src, "jcapitab.h"), "w") as f:
    f.write("\n".join(h) + "\n")
print("%d packages, %d classes, %d methods -> %s" % (len(pkgs), len(classes), len(natives), os.path.normpath(src)))
