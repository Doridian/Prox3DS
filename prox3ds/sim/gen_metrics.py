#!/usr/bin/env python3
"""Writes metrics.h: glyph advances at citro2d scale 1 for the stand-in font (see README).

NanumGothic at 26.8 px matched the 3DS system font's text widths within ~5% on real screenshots;
digits are set to the system font's 17.
"""
import sys
from PIL import ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/NanumGothic.ttf"
SIZE = 26.8
BUTTON = 25  # E000-E07E button glyphs, measured on screenshots

f = ImageFont.truetype(FONT, 400)
adv = [0] * 128
for c in range(32, 127):
    adv[c] = 17 if chr(c).isdigit() else round(f.getlength(chr(c)) / 400 * SIZE)  # the system font's are whole
with open("metrics.h", "w") as out:
    out.write("// Generated by gen_metrics.py\n#pragma once\n")
    out.write(f"#define SIM_FONT_SIZE {SIZE}f\n#define SIM_BUTTON_ADV {BUTTON}\n#define SIM_LINE 30.0f\n")
    out.write("static const unsigned char simAdv[128] = {\n")
    for i in range(0, 128, 8):
        out.write("\t" + " ".join(f"{a:2d}," for a in adv[i:i + 8]) + "\n")
    out.write("};\n")
